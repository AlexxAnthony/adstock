import numpy as np
import plotly.graph_objects as go
import streamlit as st

from common import COLOURS, NAMES, PLOT_LAYOUT, CHANNELS, footer, gbp, interval, load, page_setup
from adstock.planner import HORIZON, current_weekly_spend, forecast

page_setup(
    "Scenario planner - next quarter forecast",
    f"Set a weekly spend for each channel and see the forecast for the next {HORIZON} weeks, "
    "compared with carrying on as now (*business as usual*: each channel at its average weekly "
    "spend over the last year). Carryover from recent campaigns is included.",
)
meta, post, df, fitted = load()
cur = current_weekly_spend(df)

st.sidebar.header("Weekly spend plan")
if st.sidebar.button("Reset to business as usual"):
    for c in CHANNELS:
        st.session_state[c] = int(round(cur[CHANNELS.index(c)] / 100) * 100)
plan = np.array([
    st.sidebar.slider(NAMES[k], 0, int(max(cur[k] * 3, 5000) // 100 * 100), key=c,
                      value=st.session_state.get(c, int(round(cur[k] / 100) * 100)), step=100)
    for k, c in enumerate(CHANNELS)
], dtype=float)


@st.cache_data(show_spinner=False)
def run(plan_tuple):
    f = forecast(post, df, np.array(plan_tuple))
    return {k: v for k, v in f.items()}


f_plan = run(tuple(plan))
f_bau = run(tuple(np.round(cur / 100) * 100))

q_plan = f_plan["mu"].sum(1)
q_bau = f_bau["mu"].sum(1)
delta = q_plan - q_bau  # same draws, so baseline uncertainty cancels out
extra_spend = f_plan["spend"] - f_bau["spend"]

c1, c2, c3, c4 = st.columns(4)
c1.metric("Quarter revenue forecast", gbp(f_plan["total_revenue"].mean()),
          help=interval(f_plan["total_revenue"]))
c2.metric("Quarter media spend", gbp(f_plan["spend"]), delta=(gbp(extra_spend) + " vs BAU") if abs(extra_spend) > 1 else None,
          delta_color="off")
c3.metric("Revenue vs business as usual", gbp(delta.mean()), help=interval(delta))
c4.metric("Media ROI of this plan", f"£{(f_plan['incremental'] / max(f_plan['spend'], 1)).mean():.2f} per £1",
          help="Revenue generated by this quarter's spend (including carryover within the quarter) / spend.")
if abs(extra_spend) > 1:
    marg = delta / extra_spend
    st.info(f"Each extra £1 versus BAU returns about **£{marg.mean():.2f}** "
            f"(90% interval £{np.percentile(marg, 5):.2f} to £{np.percentile(marg, 95):.2f}).")

fig = go.Figure()
x = f_plan["dates"]
lo, hi = np.percentile(f_plan["pred"], [5, 95], axis=0)
hist = df.tail(26)
fig.add_trace(go.Scatter(x=hist["date"], y=hist["revenue"], name="Actual (last 26 weeks)",
                         line=dict(color="black")))
fig.add_trace(go.Scatter(x=x, y=hi, mode="lines", line=dict(width=0), showlegend=False, hoverinfo="skip"))
fig.add_trace(go.Scatter(x=x, y=lo, mode="lines", line=dict(width=0), fill="tonexty", name="90% forecast interval",
                         fillcolor="rgba(31,78,121,0.15)", hoverinfo="skip"))
fig.add_trace(go.Scatter(x=x, y=f_bau["mu"].mean(0), name="Business as usual",
                         line=dict(color="grey", dash="dash")))
fig.add_trace(go.Scatter(x=x, y=f_plan["mu"].mean(0), name="Your plan", line=dict(color="#1f4e79", width=3)))
fig.update_layout(height=420, yaxis_title="Weekly revenue (£)", **PLOT_LAYOUT)
st.plotly_chart(fig, width="stretch")

st.subheader("Media revenue by channel under your plan")
fig = go.Figure()
for k, c in enumerate(CHANNELS):
    fig.add_trace(go.Bar(x=x, y=f_plan["media"][:, :, k].mean(0), name=NAMES[k], marker_color=COLOURS[c]))
fig.update_layout(barmode="stack", height=320, yaxis_title="£ per week", **PLOT_LAYOUT)
st.plotly_chart(fig, width="stretch")

with st.expander("Forecast assumptions"):
    st.markdown("""
- Competitor/market sales and newsletter volume for the coming weeks are unknown, so they are set
  to the **same weeks last year**. Their own uncertainty is not included, so real-world intervals
  would be wider.
- Spend is held constant each week. Flighted (on/off) campaigns hit saturation harder, so the
  same budget spread evenly tends to earn more.
- The trend and seasonality are extrapolated from four years of history.
""")
footer()
